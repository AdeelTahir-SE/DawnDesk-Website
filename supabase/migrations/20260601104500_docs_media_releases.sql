create extension if not exists "pgcrypto";

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create table if not exists public.documentation_pages (
  slug text primary key references public.sub_apps(slug) on delete cascade,
  title text not null,
  summary text not null,
  content text not null,
  updated_at timestamptz not null default now()
);

create table if not exists public.media_uploads (
  id uuid primary key default gen_random_uuid(),
  file_name text not null,
  bucket text not null default 'site-media',
  storage_path text not null,
  public_url text not null,
  content_type text,
  size_bytes bigint,
  created_at timestamptz not null default now()
);

create table if not exists public.app_releases (
  id bigint generated by default as identity primary key,
  platform text not null check (platform in ('windows', 'macos', 'linux')),
  version text not null,
  label text not null,
  arch text not null,
  url text not null,
  is_recommended boolean not null default false,
  is_active boolean not null default true,
  published_at date not null default current_date,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(platform, version, arch)
);

drop trigger if exists documentation_pages_set_updated_at on public.documentation_pages;

create trigger documentation_pages_set_updated_at
before update on public.documentation_pages
for each row
execute function public.set_updated_at();

drop trigger if exists app_releases_set_updated_at on public.app_releases;

create trigger app_releases_set_updated_at
before update on public.app_releases
for each row
execute function public.set_updated_at();

alter table public.documentation_pages enable row level security;
alter table public.media_uploads enable row level security;
alter table public.app_releases enable row level security;

drop policy if exists "Public can read documentation pages" on public.documentation_pages;

create policy "Public can read documentation pages"
on public.documentation_pages
for select
using (true);

drop policy if exists "Public can read media uploads" on public.media_uploads;

create policy "Public can read media uploads"
on public.media_uploads
for select
using (true);

drop policy if exists "Public can read app releases" on public.app_releases;

create policy "Public can read app releases"
on public.app_releases
for select
using (is_active = true);

