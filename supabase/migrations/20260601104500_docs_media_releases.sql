insert into public.documentation_pages (
  slug,
  title,
  summary,
  content
)
select
  sub_apps.slug,
  sub_apps.name || ' Documentation',
  coalesce(sub_apps.content->>'detail', sub_apps.content->>'summary', ''),
  '## Overview

' || coalesce(sub_apps.content->>'summary', '') || '

## Key features

' || coalesce((
    select string_agg(
      '- **' || coalesce(feature_item.feature->>'title', '') || '**: ' || coalesce(feature_item.feature->>'copy', ''),
      E'\n'
      order by feature_item.ordinality
    )
    from jsonb_array_elements(
      coalesce(sub_apps.content->'features', '[]'::jsonb)
    ) with ordinality as feature_item(feature, ordinality)
  ), '') || '

## Workflow

' || coalesce((
    select string_agg(
      workflow_item.ordinality::text || '. ' || coalesce(workflow_item.step #>> '{}', ''),
      E'\n'
      order by workflow_item.ordinality
    )
    from jsonb_array_elements(
      coalesce(sub_apps.content->'workflow', '[]'::jsonb)
    ) with ordinality as workflow_item(step, ordinality)
  ), '') || '

```mermaid
flowchart TD
  Open[Open workspace] --> Work[Complete focused work]
  Work --> Save[Save output]
  Save --> Reuse[Reuse in DawnDesk]

  ```
  '
  from public.sub_apps as sub_apps
on conflict (slug) do update set
title = excluded.title,
summary = excluded.summary,
content = excluded.content,
updated_at = now();